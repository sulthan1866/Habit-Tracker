package com.habit.tracker.habitTracker.controller;

import java.util.Map;

import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.CrossOrigin;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RestController;

import com.fasterxml.jackson.core.JsonProcessingException;
import com.fasterxml.jackson.databind.JsonMappingException;
import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import com.habit.tracker.habitTracker.service.AiService;
import com.habit.tracker.habitTracker.service.DBService;

@RestController
@RequestMapping("api/v1/{userID}")
@CrossOrigin("${FRONT_END}")
public class AiController {

    @Autowired
    AiService aiService;

    @Autowired
    DBService dbService;

    JsonNode jsonNode;
    JsonNode jsonNode2;

    @Autowired
    ObjectMapper objectMapper;

    @PostMapping("/generate")
    public ResponseEntity<String> getAiText(@RequestBody Map<String, String> prompt) {
        String response = aiService.getText(
                "Write a plain SQL query to insert data into the 'days' table.The schema is as follows: "
                        +
                        "is_completed boolean, always set to false. " +
                        "date date, set to NULL. " +
                        "habitid bigint, set to 1. " +
                        "id bigint, autogenerated. " +
                        "today integer, values from 0 to " + Integer.toString(10) + ". " +
                        "tasks ARRAY, an array of AI-generated strings for task suggestions: " + prompt.get("prompt")
                        + ". " +
                        "Return 'failed' if the habit name is invalid. " +
                        "note text, set to an empty string ''. " +
                        "The query should iterate over 'today' values, ensure valid syntax, and avoid SQL grammar errors.");
        System.out.println("querry = " + response);

        try {
            jsonNode = objectMapper.readTree(response);
        } catch (JsonMappingException e) {
            System.out.println("Error processing JSON: " + e.getMessage());
        } catch (JsonProcessingException e) {
            System.out.println("Error processing JSON: " + e.getMessage());
        }
        String querry = jsonNode.path("answer").asText();

        dbService.insert(querry);

        String tableResponse = aiService
                .getText(querry + " stimulate this querry as a table only with tasks column and serial number.");
        try {
            jsonNode2 = objectMapper.readTree(tableResponse);
        } catch (JsonMappingException e) {
            System.out.println("Error processing JSON: " + e.getMessage());
        } catch (JsonProcessingException e) {
            System.out.println("Error processing JSON: " + e.getMessage());
        }
        String table = jsonNode2.path("answer").asText();

        System.out.println("querry = " + querry);
        System.out.println("table = " + tableResponse);
        System.out.println("table = " + table);
        return new ResponseEntity<>(table, HttpStatus.ACCEPTED);
    }

}
